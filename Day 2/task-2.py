# Arithmetic operators
a = 3
b = 2
print("Addition")
print(a + b)  # Addition

print("Subtraction")
print(a - b)  # Subtraction

print("Multiplication")
print(a * b)  # Multiplication

print("Division")
print(a / b)  # Division by default float value will return after division

print("Floor Division")
print(a // b)  # Floor division will return integer value after division

print("Modulo")
print(a % b)  # Modulus will return remainder after division

print("Exponentiation")
print(a ** b)  # Exponentiation will return power of a number

# PEMDAS (Parentheses, Exponents, Multiplication, Division, Addition, Subtraction)

print(3 * (3 + 3) / 3 - 3)